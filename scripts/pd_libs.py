#!/usr/bin/env python3
"""Regenerates third_party/pd-libs/generated/ after the vendored cyclone or
ELSE sources change: which files the plugin helper builds, a header per
library that prefixes every global name (so the two libraries, and libpd,
can be linked into one binary without clashes), and the list of object
setup functions to call.

Needs a C compiler (cc) and nm; run on Linux or macOS:

    python3 scripts/pd_libs.py
"""

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "third_party" / "pd-libs"
OUT = ROOT / "generated"

FLAGS = [
    "-DPD_FLOATSIZE=64",
    "-DPDINSTANCE=1",
    "-DPDTHREADS=1",
    "-DHAVE_UNISTD_H=1",
    "-w",
    "-I", str(ROOT / "pd-src"),
    "-I", str(ROOT),
    "-include", str(ROOT / "gui_compat.h"),
]

LIBS = {
    "cyclone": {
        "objects": ["cyclone/cyclone_objects/binaries"],
        "shared": ["cyclone/shared/common", "cyclone/shared/control", "cyclone/shared/signal"],
        "include": ["cyclone/shared", "cyclone/cyclone_objects/binaries"],
        # Included by scope.c, not built on its own.
        "skip": {"scope_dialog.c"},
    },
    "else": {
        "objects": ["else/Source/Control", "else/Source/Audio", "else/Source/Extra/Aliases"],
        "shared": ["else/Source/Shared"],
        "include": ["else/Source/Shared", "else/Source/Extra"],
        "skip": set(),
    },
}

# Globals two files of one library both define.
PER_FILE = {"def_font"}


def sources(lib, kind):
    out = []
    for d in LIBS[lib][kind]:
        for p in sorted((ROOT / d).rglob("*.c") if kind == "objects" else (ROOT / d).glob("*.c")):
            if p.name not in LIBS[lib]["skip"] and "/Extra/" not in str(p).replace("/Extra/Aliases/", "/"):
                out.append(p)
    return out


def ident(path):
    return re.sub(r"[^A-Za-z0-9]", "_", path.stem)


def compile_one(lib, src, obj):
    cmd = ["cc", "-c", "-fPIC", *FLAGS]
    for inc in LIBS[lib]["include"]:
        cmd += ["-I", str(ROOT / inc)]
    for name in PER_FILE:
        cmd.append(f"-D{name}={lib}_{name}_{ident(src)}")
    cmd += [str(src), "-o", str(obj)]
    return subprocess.run(cmd, capture_output=True, text=True)


def globals_of(obj):
    out = subprocess.run(["nm", "-g", "--defined-only", str(obj)], capture_output=True, text=True).stdout
    names = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "TDBRSC":
            name = parts[2]
            if sys.platform == "darwin" and name.startswith("_"):
                name = name[1:]
            names.append(name)
    return names


def main():
    OUT.mkdir(exist_ok=True)
    tmp = Path(tempfile.mkdtemp())
    source_lines = []
    setups = {}
    for lib in LIBS:
        names = set()
        lib_setups = []
        for kind in ("shared", "objects"):
            for src in sources(lib, kind):
                obj = tmp / f"{lib}-{abs(hash(str(src)))}.o"
                r = compile_one(lib, src, obj)
                rel = src.relative_to(ROOT)
                if r.returncode != 0:
                    print(f"skip {rel}: {r.stderr.strip().splitlines()[0] if r.stderr else 'failed'}")
                    continue
                source_lines.append(f"{lib}\t{rel}")
                found = [n for n in globals_of(obj) if n not in PER_FILE and not n.startswith(tuple(f"{lib}_{p}" for p in PER_FILE))]
                names.update(found)
                if kind == "objects":
                    text = src.read_text(errors="replace")
                    for n in found:
                        # Capitalised setups (cyclone's [Clip~] and so on) are old
                        # Max spellings that only print a deprecation error.
                        if (n.startswith("setup_") or n.endswith("_setup")) and not n[0].isupper() and re.search(
                            rf"\b{re.escape(n)}\s*\(\s*void\s*\)", text
                        ):
                            lib_setups.append(n)
        with open(OUT / f"names_{lib}.h", "w") as f:
            f.write(f"/* Generated by scripts/pd_libs.py: every global name in {lib},\n"
                    f"   prefixed, so it can't clash with the other library or libpd. */\n")
            for n in sorted(names):
                f.write(f"#define {n} {lib}_{n}\n")
        setups[lib] = sorted(set(lib_setups))
    with open(OUT / "sources.txt", "w") as f:
        f.write("# Generated by scripts/pd_libs.py: library and file, one per line.\n")
        f.write("\n".join(source_lines) + "\n")
    with open(OUT / "setups.h", "w") as f:
        f.write("/* Generated by scripts/pd_libs.py: each library's object setups. */\n")
        for lib, names in setups.items():
            for n in names:
                f.write(f"extern void {lib}_{n}(void);\n")
            f.write(f"#define {lib.upper()}_SETUPS \\\n")
            f.write("".join(f"    {lib}_{n}(); \\\n" for n in names))
            f.write("\n")
    print(f"{len(source_lines)} files; setups: " + ", ".join(f"{k} {len(v)}" for k, v in setups.items()))


if __name__ == "__main__":
    main()
